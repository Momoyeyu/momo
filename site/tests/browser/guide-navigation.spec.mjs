import { test, expect } from '@playwright/test'
import { copy, localePath } from '../../docs/.vitepress/theme/product-copy.mjs'

const names = { zh: ['首页', '使用帮助'], en: ['Home', 'Guides'], ja: ['ホーム', '使い方'] }
const guidePath = (slug, code = 'zh') => `/momo/help/${slug}${code === 'zh' ? '' : `?lang=${code}`}`
const globalNav = page => page.getByTestId('global-navigation')
const guideNav = page => page.getByTestId('guide-navigation')
const noOverflow = async page => {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}

for (const code of ['zh', 'en', 'ja']) {
  test(`desktop: ${code} global navigation stays at the same level through the guide routes`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`/momo${localePath(code)}`)
    const nav = globalNav(page)
    await expect(nav.getByRole('link')).toHaveText(names[code])
    await expect(nav.getByRole('link', { name: names[code][0], exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(nav.getByRole('link', { name: names[code][1], exact: true })).not.toHaveAttribute('aria-current')
    await nav.getByRole('link', { name: names[code][1], exact: true }).click()
    await expect(page).toHaveURL(guidePath('getting-started', code))
    await expect(page.locator('.help-page article h1')).toHaveText('初次见面')
    await expect(nav.getByRole('link')).toHaveText(names[code])
    await expect(nav.getByRole('link', { name: names[code][1], exact: true })).toHaveAttribute('aria-current', 'page')
    await guideNav(page).getByRole('link', { name: copy[code].helpNav[1], exact: true }).click()
    await expect(page).toHaveURL(guidePath('voice', code))
    await expect(page.locator('.help-page article h1')).toHaveText('让 momo 开口说话')
    await expect(guideNav(page).locator('[aria-current="page"]')).toHaveText(`02${copy[code].helpNav[1]}`)
    // Guides represents the current section; its landing page is a different route.
    await expect(nav.getByRole('link', { name: names[code][1], exact: true })).toHaveAttribute('aria-current', 'true')
    await guideNav(page).getByRole('link', { name: copy[code].helpNav[2], exact: true }).click()
    await expect(page).toHaveURL(guidePath('data', code))
    await expect(guideNav(page).locator('[aria-current="page"]')).toHaveCount(1)
    await expect(page.locator('.help-page article')).toHaveAttribute('lang', 'zh-CN')
    await expect(page.locator('.wordmark')).toHaveAttribute('href', `/momo${localePath(code)}`)
    if (code !== 'zh') await expect(page.locator('.translation-note')).toHaveText(copy[code].helpNote)
    await noOverflow(page)
    await nav.getByRole('link', { name: names[code][0], exact: true }).click()
    await expect(page).toHaveURL(`/momo${localePath(code)}`)
    await expect(nav.getByRole('link', { name: names[code][0], exact: true })).toHaveAttribute('aria-current', 'page')
  })
}

test('desktop: guide language roundtrip retains the article route and localized guide links', async ({ page }) => {
  await page.goto(guidePath('voice'))
  const menu = page.getByTestId('language-menu')
  for (const code of ['en', 'ja', 'zh']) {
    await menu.locator('summary').click()
    await expect(page.getByTestId(`locale-${code}`)).toHaveAttribute('href', guidePath('voice', code))
    await page.getByTestId(`locale-${code}`).click()
    await expect(page).toHaveURL(guidePath('voice', code))
    await expect(page.locator('.help-page article h1')).toHaveText('让 momo 开口说话')
    await expect(globalNav(page).getByRole('link')).toHaveText(names[code])
    await expect(guideNav(page).getByRole('link', { name: copy[code].helpNav[2], exact: true })).toHaveAttribute('href', guidePath('data', code))
    if (code !== 'zh') await expect(page.locator('.translation-note')).toHaveText(copy[code].helpNote)
    else await expect(page.locator('.translation-note')).toHaveCount(0)
  }
})

test('desktop: guide index and long-form content fit a large desktop viewport', async ({ page }) => {
  await page.setViewportSize({ width: 1938, height: 1080 })
  await page.goto(guidePath('voice', 'en'))
  await expect(globalNav(page).getByRole('link', { name: 'Home', exact: true })).toBeVisible()
  await expect(globalNav(page).getByRole('link', { name: 'Guides', exact: true })).toBeVisible()
  const index = await guideNav(page).boundingBox()
  const article = await page.locator('.help-page article').boundingBox()
  expect(index.x + index.width).toBeLessThan(article.x)
  expect(article.width).toBeLessThanOrEqual(760)
  await expect(page.locator('.help-atmosphere img')).toHaveAttribute('src', '/momo/brand/momo-presence-v2.webp')
  await noOverflow(page)
})

test('desktop: changing guide articles drops the previous article hash from language links', async ({ page }) => {
  await page.goto('/momo/help/voice')
  const heading = await page.locator('.help-page article h2').first().getAttribute('id')
  await page.goto(`/momo/help/voice#${encodeURIComponent(heading)}`)
  await guideNav(page).getByRole('link', { name: '备份与迁移', exact: true }).click()
  await expect(page).toHaveURL('/momo/help/data')
  await page.getByTestId('language-menu').locator('summary').click()
  await expect(page.getByTestId('locale-en')).toHaveAttribute('href', '/momo/help/data?lang=en')
  await page.getByTestId('locale-en').click()
  await expect(page).toHaveURL('/momo/help/data?lang=en')
  await expect(page.locator('.help-page article h1')).toBeInViewport()
})

test('mobile: both global routes and the language menu remain keyboard usable without overflow', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 })
  await page.goto('/momo/')
  const nav = globalNav(page)
  await expect(nav.getByRole('link', { name: '首页', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: '使用帮助', exact: true })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: '跳到正文', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(nav.getByRole('link', { name: '首页', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(nav.getByRole('link', { name: '使用帮助', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(guidePath('getting-started'))
  const summary = page.getByTestId('language-menu').locator('summary')
  await summary.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('language-menu')).toHaveAttribute('open', '')
  await page.keyboard.press('Escape')
  await expect(summary).toBeFocused()
  await expect(page.getByTestId('language-menu')).not.toHaveAttribute('open', '')
  await summary.press('Enter')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(page.getByTestId('locale-en')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(guidePath('getting-started', 'en'))
  await guideNav(page).getByRole('link', { name: 'Voice', exact: true }).press('Enter')
  await expect(page).toHaveURL(guidePath('voice', 'en'))
  await expect(nav.getByRole('link', { name: 'Home', exact: true })).toBeVisible()
  await expect(nav.getByRole('link', { name: 'Guides', exact: true })).toBeVisible()
  await noOverflow(page)
  await page.locator('.help-page article pre').first().scrollIntoViewIfNeeded()
  await noOverflow(page)
})
