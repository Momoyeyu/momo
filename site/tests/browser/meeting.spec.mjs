test('desktop: a superseded image decode cannot clear the replacement particle renderer',async({page})=>{
  await page.setViewportSize({width:1440,height:1000})
  await page.addInitScript(()=>{
    const decode=HTMLImageElement.prototype.decode
    let first=true
    HTMLImageElement.prototype.decode=function(...args){
      const decoded=decode.apply(this,args)
      if(first && this.src.includes('momo-presence-v2')){
        first=false
        return decoded.then(()=>new Promise(resolve=>{window.releaseFirstMeetingDecode=resolve}))
      }
      return decoded
    }
  })
  await page.goto('./')
  await expect.poll(()=>page.evaluate(()=>typeof window.releaseFirstMeetingDecode)).toBe('function')
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(page.getByTestId('meeting-runway')).not.toHaveClass(/has-motion/)
  await page.emulateMedia({reducedMotion:'no-preference'})
  const canvas=page.getByTestId('meeting-pixels')
  await expect(canvas).toHaveAttribute('data-ready','true')
  await progress(page,.36)
  const plate=await canvas.evaluate(el=>el.toDataURL())
  await page.evaluate(async()=>{window.releaseFirstMeetingDecode();await new Promise(resolve=>setTimeout(resolve,0))})
  expect(await canvas.evaluate(el=>el.width)).toBeGreaterThan(0)
  expect(await canvas.evaluate(el=>el.toDataURL())).toBe(plate)
})

