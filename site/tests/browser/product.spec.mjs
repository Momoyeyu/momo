test('mobile: touch swipes change the real stack without clipping content', async ({page,context})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('./')
  const deck=page.getByTestId('moment-deck');await deck.scrollIntoViewIfNeeded()
  const box=await deck.boundingBox();const client=await context.newCDPSession(page)
  const y=Math.round(box.y+box.height*.52),start=Math.round(box.x+box.width*.85),end=Math.round(box.x+box.width*.2)
  await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:start,y}]})
  for(let i=1;i<=6;i++)await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:Math.round(start+(end-start)*i/6),y}]})
  await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(page.getByTestId('deck-status')).toHaveText('慢慢积累的记忆')
  await noOverflow(page)
  await page.screenshot({path:`${evidence}/mobile-memory.png`,fullPage:true,animations:'disabled'})
  await page.getByTestId('deck-next').click()
  await expect(page.getByTestId('deck-status')).toHaveText('你的相处方式')
  const card=page.locator('[data-position="active"]')
  expect(await card.evaluate(el=>el.scrollHeight<=el.clientHeight+2)).toBe(true)
  await page.screenshot({path:`${evidence}/mobile.png`,fullPage:true,animations:'disabled'})
  await client.detach()
})

test('reduced motion: no unsolicited video download; font failure, keyboard and explicit play work', async ({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.setViewportSize({width:320,height:720})
  const media=[];page.on('request',r=>{if(r.url().endsWith('.webm'))media.push(r.url())})
  await page.route('**/*.woff2',r=>r.abort())
  await page.goto('./')
  await expect(page.getByRole('heading',{level:1})).toBeVisible()
  await noOverflow(page)
  await page.waitForTimeout(300) // Give visibility observers time to request media if preference gating regresses.
  await expect(page.getByTestId('hero-video')).not.toHaveAttribute('src')
  expect(media).toEqual([])
  expect(await page.locator('html').evaluate(el=>getComputedStyle(el).scrollBehavior)).toBe('auto')
  await page.keyboard.press('Tab');await expect(page.getByRole('link',{name:'跳到正文'})).toBeFocused()
  await page.getByTestId('video-toggle').click()
  await expect.poll(()=>page.getByTestId('hero-video').evaluate(v=>!v.paused&&v.currentTime>0)).toBe(true)
  await page.getByTestId('deck-next').click()
  await expect(page.getByTestId('hero-video')).toHaveJSProperty('paused',true)
  await noOverflow(page)
  expect(await page.locator('[data-position="active"]').evaluate(el=>el.scrollHeight<=el.clientHeight+2)).toBe(true)
  await page.screenshot({path:`${evidence}/mobile-font-failure-reduced-motion.png`,fullPage:true,animations:'disabled'})
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.addInitScript(()=>Object.defineProperty(navigator,'connection',{configurable:true,value:{saveData:true,addEventListener(){},removeEventListener(){}}}))
  const before=media.length
  await page.goto('./')
  await page.waitForTimeout(300) // Give visibility observers time to request media if preference gating regresses.
  await expect(page.getByTestId('hero-video')).not.toHaveAttribute('src')
  expect(media.length).toBe(before)
})
