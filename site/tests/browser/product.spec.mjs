const helpPaths = ['help/getting-started', 'help/voice', 'help/data']
async function checkInternalLinks(page, request) {
  const origin = new URL(page.url()).origin
  const links = [...new Set(await page.locator('a[href]').evaluateAll(els => els.map(a => a.href)))]
  for (const href of links) {
    const url = new URL(href)
    if (url.origin !== origin) continue
    expect(url.pathname.startsWith('/momo/'),href).toBe(true)
    const response = await request.get(url.href)
    expect(response.status(), href).toBe(200)
    if (url.hash) {
      const html = await response.text()
      expect(html.includes(`id="${decodeURIComponent(url.hash.slice(1))}"`), href).toBe(true)
    }
  }
}
async function noOverflow(page) {
  const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,offenders:[...document.querySelectorAll('body *')].map(el=>({name:el.tagName+'.'+el.className,left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right})).filter(el=>el.right>innerWidth+1||el.left< -1).slice(0,20)}))
  expect(layout.scroll<=layout.width,JSON.stringify(layout)).toBe(true)
}

